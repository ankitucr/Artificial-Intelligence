import json
import os
from typing import Any, Literal, Optional

import pyseto
from fastapi import FastAPI, Header
from pydantic import BaseModel, Field
from pyseto import Key

from cda.shared.models import (
    Axis1ActionVerdict,
    Axis2EvaluationEvidence,
)

app = FastAPI(
    title="Cognitive Decision Architecture Enforcement Gate",
    version="2.0.0",
    description=(
        "Runtime enforcement boundary validating Two-Axis PASETO v4 leases, "
        "Syntactic Payload Locks, Circuit Breakers, and generating 3-State Execution Traces."
    )
)

SECRET_HEX = os.getenv(
    "CDA_SECRET_HEX",
    "707172737475767778797a7b7c7d7e7f808182838485868788898a8b8c8d8e8f"
)
PASETO_KEY = Key.new(version=4, purpose="local", key=bytes.fromhex(SECRET_HEX))

FinalExecutionState = Literal["EXECUTED", "BLOCKED", "REMEDIATED"]


class ExecutionRequest(BaseModel):
    """Payload incoming to the Enforcement Gate alongside the authorization token."""
    target_service: str = Field(..., json_schema_extra={"example": "payment_gateway"})
    action: str = Field(..., json_schema_extra={"example": "transfer_funds"})
    params: dict[str, Any] = Field(default_factory=dict)
    global_context_freeze: bool = Field(
        False, description="Simulates a stale context or TOCTOU drift detected by the Gate."
    )


class GateExecutionTrace(BaseModel):
    """Forensic audit trace generated by the Gate after enforcing a decision."""
    intent_id: str
    final_state: FinalExecutionState
    axis_1_action_verdict: Axis1ActionVerdict
    axis_2_evaluation_evidence: Axis2EvaluationEvidence
    executed_payload: dict[str, Any]
    enforcement_timestamp: str
    decision_reason: str


class CircuitBreaker:
    """In-memory rate and behavior tracker enforcing operational circuit breaking."""
    def __init__(self, max_requests_per_window: int = 100) -> None:
        self.max_requests = max_requests_per_window
        self.request_counts: dict[str, int] = {}
        self.tripped_agents: set[str] = set()

    def is_tripped(self, agent_id: str) -> bool:
        return agent_id in self.tripped_agents

    def record_request(self, agent_id: str) -> bool:
        count = self.request_counts.get(agent_id, 0) + 1
        self.request_counts[agent_id] = count
        if count > self.max_requests:
            self.tripped_agents.add(agent_id)
            return False
        return True

    def reset(self, agent_id: Optional[str] = None) -> None:
        if agent_id:
            self.request_counts.pop(agent_id, None)
            self.tripped_agents.discard(agent_id)
        else:
            self.request_counts.clear()
            self.tripped_agents.clear()


GLOBAL_CIRCUIT_BREAKER = CircuitBreaker()


@app.post("/execute", response_model=GateExecutionTrace)
def execute_action(
    request: ExecutionRequest,
    authorization: Optional[str] = Header(None, alias="Authorization")
) -> GateExecutionTrace:
    """
    Enforces operational governance at the execution boundary.
    """
    now_iso = datetime.datetime.now(datetime.timezone.utc).isoformat()

    # 1. Missing Authorization Token
    if not authorization or not authorization.startswith("Bearer "):
        axis_1 = Axis1ActionVerdict(state="BLOCK", fallback_action="BLOCK", remediation_details=None)
        axis_2 = Axis2EvaluationEvidence(
            execution_status="INVALID_TOKEN",
            checks_executed=["GATE-TOKEN-PRESENT"],
            failure_mode="MISSING_BEARER_TOKEN"
        )
        return GateExecutionTrace(
            intent_id="UNKNOWN",
            final_state="BLOCKED",
            axis_1_action_verdict=axis_1,
            axis_2_evaluation_evidence=axis_2,
            executed_payload={},
            enforcement_timestamp=now_iso,
            decision_reason="Enforcement rejected: Missing or malformed Authorization header."
        )

    raw_token = authorization.split("Bearer ")[1].strip()

    # 2. Cryptographic Token Decryption and Claims Validation
    try:
        decoded_paseto = pyseto.decode(PASETO_KEY, raw_token)
        raw_payload = decoded_paseto.payload
        payload = json.loads(raw_payload.decode("utf-8")) if isinstance(raw_payload, bytes) else raw_payload
    except Exception as err:  # noqa: BLE001
        axis_1 = Axis1ActionVerdict(state="BLOCK", fallback_action="BLOCK", remediation_details=None)
        axis_2 = Axis2EvaluationEvidence(
            execution_status="INVALID_TOKEN",
            checks_executed=["GATE-TOKEN-VERIFY"],
            failure_mode=f"PASETO_DECODE_ERROR: {err!s}"
        )
        return GateExecutionTrace(
            intent_id="UNKNOWN",
            final_state="BLOCKED",
            axis_1_action_verdict=axis_1,
            axis_2_evaluation_evidence=axis_2,
            executed_payload={},
            enforcement_timestamp=now_iso,
            decision_reason=f"Enforcement rejected: Cryptographic token validation failed ({err!s})."
        )

    intent_id = payload.get("intent_id", "UNKNOWN")
    agent_id = payload.get("agent_id", "UNKNOWN")
    authorized_params = payload.get("params", {})

    raw_axis_1 = payload.get("axis_1_action_verdict", {})
    raw_axis_2 = payload.get("axis_2_evaluation_evidence", {})

    axis_1 = (
        Axis1ActionVerdict(**raw_axis_1)
        if raw_axis_1
        else Axis1ActionVerdict(state="PERMIT", fallback_action=None, remediation_details=None)
    )
    axis_2 = (
        Axis2EvaluationEvidence(**raw_axis_2)
        if raw_axis_2
        else Axis2EvaluationEvidence(execution_status="COMPLETE", checks_executed=["GATE-EXEC"], failure_mode=None)
    )

    token_action_state = axis_1.state

    # 3. Behavioral Circuit Breaker Check
    if GLOBAL_CIRCUIT_BREAKER.is_tripped(agent_id):
        axis_1_blocked = Axis1ActionVerdict(state="BLOCK", fallback_action="BLOCK", remediation_details=None)
        axis_2_blocked = Axis2EvaluationEvidence(
            execution_status="UNRESOLVED_DEPENDENCY_OR_STALE_CONTEXT",
            checks_executed=["GATE-CIRCUIT-BREAKER"],
            failure_mode="CIRCUIT_BREAKER_TRIPPED"
        )
        return GateExecutionTrace(
            intent_id=intent_id,
            final_state="BLOCKED",
            axis_1_action_verdict=axis_1_blocked,
            axis_2_evaluation_evidence=axis_2_blocked,
            executed_payload={},
            enforcement_timestamp=now_iso,
            decision_reason=f"Enforcement rejected: Behavioral Circuit Breaker active for agent '{agent_id}'."
        )

    GLOBAL_CIRCUIT_BREAKER.record_request(agent_id)

    # 4. Syntactic Payload Lock Check (Only enforced for standard PERMIT verdicts)
    if token_action_state != "REMEDIATE" and request.params:
        for key, val in request.params.items():
            if key in authorized_params and authorized_params[key] != val:
                axis_1_blocked = Axis1ActionVerdict(state="BLOCK", fallback_action="BLOCK", remediation_details=None)
                axis_2_blocked = Axis2EvaluationEvidence(
                    execution_status="UNRESOLVED_DEPENDENCY_OR_STALE_CONTEXT",
                    checks_executed=["GATE-SYNTACTIC-LOCK"],
                    failure_mode="PAYLOAD_TAMPERING_DETECTED"
                )
                return GateExecutionTrace(
                    intent_id=intent_id,
                    final_state="BLOCKED",
                    axis_1_action_verdict=axis_1_blocked,
                    axis_2_evaluation_evidence=axis_2_blocked,
                    executed_payload={},
                    enforcement_timestamp=now_iso,
                    decision_reason=f"Enforcement rejected: Syntactic Payload Lock violation for parameter '{key}'."
                )

    # 5. Lease Expiration Check (TTL / Short Lease)
    exp_str = payload.get("exp")
    if exp_str:
        exp_dt = datetime.datetime.fromisoformat(exp_str)
        now_dt = datetime.datetime.now(datetime.timezone.utc)
        if now_dt > exp_dt:
            axis_1_blocked = Axis1ActionVerdict(state="BLOCK", fallback_action="BLOCK", remediation_details=None)
            axis_2_blocked = Axis2EvaluationEvidence(
                execution_status="EXPIRED_LEASE",
                checks_executed=["GATE-TTL-CHECK"],
                failure_mode="LEASE_EXPIRED"
            )
            return GateExecutionTrace(
                intent_id=intent_id,
                final_state="BLOCKED",
                axis_1_action_verdict=axis_1_blocked,
                axis_2_evaluation_evidence=axis_2_blocked,
                executed_payload={},
                enforcement_timestamp=now_iso,
                decision_reason="Enforcement rejected: Authorization lease has expired."
            )

    # 6. Context Drift / TOCTOU Freeze Check
    if request.global_context_freeze:
        axis_1_blocked = Axis1ActionVerdict(state="BLOCK", fallback_action="BLOCK", remediation_details=None)
        axis_2_blocked = Axis2EvaluationEvidence(
            execution_status="UNRESOLVED_DEPENDENCY_OR_STALE_CONTEXT",
            checks_executed=["GATE-CONTEXT-FRESHNESS"],
            failure_mode="TOCTOU_STALE_CONTEXT_DETECTED"
        )
        return GateExecutionTrace(
            intent_id=intent_id,
            final_state="BLOCKED",
            axis_1_action_verdict=axis_1_blocked,
            axis_2_evaluation_evidence=axis_2_blocked,
            executed_payload={},
            enforcement_timestamp=now_iso,
            decision_reason="Enforcement rejected: Global context freeze / TOCTOU drift detected at execution boundary."
        )

    # 7. Final 3-State Mapping (EXECUTED, BLOCKED, REMEDIATED)
    final_state: FinalExecutionState
    if token_action_state == "PERMIT":
        final_state = "EXECUTED"
        decision_reason = "Action successfully executed under valid PERMIT verdict."
        executed_payload = authorized_params or request.params
    elif token_action_state == "REMEDIATE":
        final_state = "REMEDIATED"
        decision_reason = "Action executed under REMEDIATE verdict with forced parameters."
        executed_payload = authorized_params  # Enforce capped parameters from Kernel
    else:
        final_state = "BLOCKED"
        decision_reason = f"Action blocked due to non-executable Axis 1 state: {token_action_state}."
        executed_payload = {}

    return GateExecutionTrace(
        intent_id=intent_id,
        final_state=final_state,
        axis_1_action_verdict=axis_1,
        axis_2_evaluation_evidence=axis_2,
        executed_payload=executed_payload,
        enforcement_timestamp=now_iso,
        decision_reason=decision_reason
    )